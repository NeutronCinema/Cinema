const_eV2kk = 1/2.072124652399821e-3
boltzmann = 8.6173303e-5   # eV/K

class SABData: #fixme single element
    def __init__(self, alpha, beta, sab, temperature):
        self.alpha = alpha
        self.beta = beta
        self.sab = sab
        self.temperature = temperature
        self.type = 'full'

    @classmethod
    def from_vdos(cls, vdos, mass, bondxs, temperature):
        
        NCrystal.vdos.analyseVDOS
        def w_fct(n):
            if n==1:
                return 1.
            else:
                return 0.

        knl = NCrystal.vdos.extractKnl(vdos, mass, temperature, plot = False, vdoslux = 2, order_weight_fct=w_fct)
        knl['sab'] *= bondxs
        return cls(knl['alpha'], knl['beta'], knl['sab'].reshape([knl['beta'].size, knl['alpha'].size]), temperature)
    
    @classmethod
    def from_px(cls, fn, temperature):
        with h5py.File(fn, "r") as f:
          en = f['en'][()]
          Q = f['q'][()]
          sqw = f['s'][()]
        kt = temperature*boltzmann                
        en = np.append([0.], en)
        sqw=np.concatenate((np.zeros([Q.size, 1]), sqw), axis=1).T

        alpha = Q*Q/(kt*const_eV2kk)
        beta = en/kt
        sab = sqw*0.5*kt*kt*const_eV2kk*300./temperature

        sab = cls(alpha, beta, sab, temperature)
        sab.type = 'sym'
        return sab

    
    def export(self, ncmatfile):
        _res=f"""NCMAT v5

@STATEOFMATTER
  liquid
  
@DENSITY
  1.0 atoms_per_aa3

@DYNINFO
  element  Si
  fraction 1
  type     scatknl
  temperature {self.temperature}
  """

        _res += ncncmat.formatVectorForNCMAT('alphagrid',self.alpha)
        _res += ncncmat.formatVectorForNCMAT('betagrid',self.beta)
        if self.type == 'full':
            _res += ncncmat.formatVectorForNCMAT('sab', self.sab)
        elif self.type == 'sym':
            _res += ncncmat.formatVectorForNCMAT('sab_scaled', (self.sab.T*np.exp(-0.5*self.beta)).T)
        else:
            raise RuntimeError()
        pathlib.Path(ncmatfile).write_text(_res)

    def plot(self):
        fig=plt.figure()
        ax = fig.add_subplot(111)
        H = self.sab
        
        if self.type == 'sym':
            X, Y = np.meshgrid(self.alpha, -self.beta)
        else:
            X, Y = np.meshgrid(self.alpha, self.beta)
        import matplotlib.colors as colors
        pcm = ax.pcolormesh(X, Y, H,  cmap=plt.cm.jet, norm=colors.LogNorm(vmin=H.max()*1e-4, vmax=H.max()),) 
        fig.colorbar(pcm, ax=ax)
        plt.xlabel('alpha')
        plt.ylabel('beta')


    def plotSumRule(self):
        if self.type == 'full': #only the negtive part, for down scattering
          h = self.beta.size//2
          sumrule = []
          for i in range(self.alpha.size):
              sumrule.append(-np.trapz(self.sab[:h,i], np.abs(self.beta[:h])))
          plt.plot(self.alpha, sumrule )
        else:
          sumrule = []
          for i in range(self.alpha.size):
              sumrule.append(np.trapz(self.sab.T[i], self.beta))
          plt.plot(self.alpha, sumrule )


